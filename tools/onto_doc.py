#!/usr/bin/env python3
"""
onto_doc.py -- reference documentation and metrics of the CLO ontology.

Reads the T-Box (clo_ontology_v8.ttl), the organisational module (clo_org.ttl) and the
type catalogue (clo_types.ttl, clo_types_ext.ttl) and writes
  docs/ontology.md       metrics, class hierarchy, properties with domain/range and
                         comments, property chains, defined classes
  docs/metrics.json      the metrics as numbers (used by the papers)

  python3 tools/onto_doc.py
"""
import collections
import json
import os

import rdflib
from rdflib.collection import Collection
from rdflib.namespace import OWL, RDF, RDFS

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CLO = "http://example.org/clo/ontology/clo#"
C = rdflib.Namespace(CLO)
ONTO = os.path.join(ROOT, "ontology")


def loc(u):
    s = str(u)
    return s.split("#")[-1] if s.startswith(CLO) else s.rsplit("/", 1)[-1].split("#")[-1]


def name(g, u):
    if isinstance(u, rdflib.BNode):
        members = list(g.objects(u, OWL.unionOf))
        if members:
            return " ⊔ ".join(loc(x) for x in Collection(g, members[0]))
        inv = next(g.objects(u, OWL.inverseOf), None)
        if inv is not None:
            return loc(inv) + "⁻"
        return "(anonymous)"
    return loc(u)


def comment(g, u):
    for c in g.objects(u, RDFS.comment):
        if getattr(c, "language", None) in (None, "en"):
            return " ".join(str(c).split())
    return ""


def main():
    tbox = rdflib.Graph()
    for f in ("clo_ontology_v8.ttl", "clo_org.ttl"):
        tbox.parse(os.path.join(ONTO, f))
    cat = rdflib.Graph()
    for f in ("clo_ontology_v8.ttl", "clo_types.ttl", "clo_types_ext.ttl"):
        cat.parse(os.path.join(ONTO, f))
    g = tbox
    own = lambda s: isinstance(s, rdflib.URIRef) and str(s).startswith(CLO)
    classes = sorted({s for s in g.subjects(RDF.type, OWL.Class) if own(s)}, key=loc)
    defined = [s for s in classes if (s, OWL.equivalentClass, None) in g]
    ops = sorted({s for s in g.subjects(RDF.type, OWL.ObjectProperty) if own(s)}, key=loc)
    dps = sorted({s for s in g.subjects(RDF.type, OWL.DatatypeProperty) if own(s)}, key=loc)
    chains = list(g.subject_objects(OWL.propertyChainAxiom))
    types = set(cat.subjects(RDF.type, C.ResourceType))
    providers = collections.Counter(loc(o) for t in types for o in cat.objects(t, C.hostedBy))
    basekinds = {o for t in types for o in cat.objects(t, C.implementsBaseKind)}
    basekinds_all = {s for s in g.subjects(RDFS.subClassOf, C.BaseKind)} | {s for s in g.subjects(C.categoryOf, None)}
    categories = set(g.subjects(RDF.type, C.FunctionalCategory))
    support = collections.Counter(str(o) for t in types for o in cat.objects(t, C.labelingSupport))
    m = {"tbox_triples": len(rdflib.Graph().parse(os.path.join(ONTO, "clo_ontology_v8.ttl"))),
         "tbox_org_triples": len(g), "classes": len(classes), "defined_classes": len(defined),
         "object_properties": len(ops), "datatype_properties": len(dps), "property_chains": len(chains),
         "transitive_properties": len(set(g.subjects(RDF.type, OWL.TransitiveProperty))),
         "functional_properties": len(set(g.subjects(RDF.type, OWL.FunctionalProperty))),
         "disjointness_axioms": len(list(g.triples((None, OWL.disjointWith, None))))
                                + len(list(g.subjects(RDF.type, OWL.AllDisjointClasses))),
         "functional_categories": len(categories), "basekinds": len(basekinds_all),
         "basekinds_used_by_types": len(basekinds), "resource_types": len(types),
         "types_by_provider": dict(providers.most_common()), "providers": len(providers),
         "tag_support": dict(support), "governance_roles": len(set(g.subjects(RDF.type, C.GovernanceRole)))}
    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    json.dump(m, open(os.path.join(ROOT, "docs", "metrics.json"), "w"), indent=1)

    L = ["# CLO ontology reference", "",
         "Generated by `tools/onto_doc.py` from `ontology/`. Namespace `" + CLO + "`. OWL 2 DL (ROBOT); "
         "operative inferences at run time: `rules/materialise.ru`.", "", "## Metrics", "",
         "| | |", "|---|---|"]
    for k, v in m.items():
        L.append(f"| {k.replace('_', ' ')} | {v} |")
    L += ["", "## Class hierarchy", ""]
    children = collections.defaultdict(list)
    for s in classes:
        sups = [o for o in g.objects(s, RDFS.subClassOf) if own(o)]
        for o in sups or [None]:
            children[o].append(s)

    def walk(c, depth):
        for s in sorted(children.get(c, []), key=loc):
            mark = " *(defined)*" if s in defined else ""
            cm = comment(g, s)
            L.append("  " * depth + f"- **{loc(s)}**{mark}" + (f" — {cm[:160]}" if cm else ""))
            if depth < 6:
                walk(s, depth + 1)
    walk(None, 0)
    L += ["", "## Object properties", "", "| Property | Domain | Range | Characteristics | Comment |", "|---|---|---|---|---|"]
    for p in ops:
        ch = [loc(t) for t in g.objects(p, RDF.type) if t in (OWL.TransitiveProperty, OWL.FunctionalProperty,
                                                           OWL.SymmetricProperty, OWL.InverseFunctionalProperty)]
        L.append(f"| `{loc(p)}` | {', '.join(name(g, d) for d in g.objects(p, RDFS.domain))} | "
                 f"{', '.join(name(g, r) for r in g.objects(p, RDFS.range))} | {', '.join(ch)} | {comment(g, p)[:200]} |")
    L += ["", "## Datatype properties", "", "| Property | Domain | Range | Comment |", "|---|---|---|---|"]
    for p in dps:
        L.append(f"| `{loc(p)}` | {', '.join(name(g, d) for d in g.objects(p, RDFS.domain))} | "
                 f"{', '.join(loc(r) for r in g.objects(p, RDFS.range))} | {comment(g, p)[:200]} |")
    L += ["", "## Property chains", ""]
    for s, o in chains:
        L.append(f"- `{' ∘ '.join(name(g, x) for x in Collection(g, o))}` ⊑ `{loc(s)}`")
    L += ["", "## Resource-type catalogue", "", f"{len(types)} types over {len(providers)} providers; "
          f"tag support: {dict(support)}. Per provider: {dict(providers.most_common())}.", ""]
    open(os.path.join(ROOT, "docs", "ontology.md"), "w").write("\n".join(L) + "\n")
    print(json.dumps(m))


if __name__ == "__main__":
    main()
